#!/usr/bin/env python
"""Generate shared/constants.js for the cg2all WebGPU port.

Reads cg2all's compiled residue constants (CHARMM36 topology, rigid groups and
rigid-body transforms per secondary-structure class), e3nn's real Wigner-3j
tensors and MDTraj's PDB name-replacement tables, and writes them as plain JS
arrays rounded to float32 (the precision cg2all uses at inference).

usage:
  python -I export_constants.py --cg2all /path/to/huhlim/cg2all --out ../shared/constants.js
Requires numpy, torch, e3nn==0.5.1 and mdtraj (no DGL needed).
"""
import argparse
import json
import sys

import numpy as np


def f32(values):
    return [float(np.format_float_positional(np.float32(v), unique=True, trim="-")) for v in np.ravel(values)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cg2all", required=True, help="checkout of github.com/huhlim/cg2all")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    sys.path[:0] = [f"{args.cg2all}/cg2all/lib"]

    import torch
    import e3nn.o3 as o3
    from mdtraj.formats.pdb import PDBTrajectoryFile
    import residue_constants as rc

    residues = {}
    for name in rc.AMINO_ACID_s:
        if name == "UNK":
            continue
        res = rc.residue_s[name]
        residues[name] = {
            "atoms": list(res.atom_s),
            "outputAtoms": list(res.output_atom_s),
            "outputIndex": [int(i) for i in res.output_atom_index],
        }

    w3j = {}
    for d_in in range(3):
        for d_out in range(3):
            for J in range(abs(d_in - d_out), d_in + d_out + 1):
                # SE3Transformer basis.get_clebsch_gordon: wigner_3j(J, d_in, d_out).permute(2, 1, 0) -> [k][l][m]
                q = o3.wigner_3j(J, d_in, d_out, dtype=torch.float64).permute(2, 1, 0).contiguous()
                w3j[f"{J},{d_in},{d_out}"] = [float(x) for x in q.reshape(-1).numpy().astype(np.float32)]

    PDBTrajectoryFile._loadNameReplacementTables()
    std = {}
    terminal = {"HT1", "HT2", "HT3", "HN1", "HN2", "OT1", "OT2"}
    for name in sorted(set(rc.AMINO_ACID_REV_s.get(n, n) for n in residues)):
        table = PDBTrajectoryFile._atomNameReplacements.get(name, {})
        emitted = terminal.union(*(residues[n]["outputAtoms"] for n in residues if rc.AMINO_ACID_REV_s.get(n, n) == name))
        std[name] = {k: v for k, v in sorted(table.items()) if k != v and k in emitted}

    transforms_dep = rc.RIGID_TRANSFORMS_DEP.numpy()
    groups_dep = rc.RIGID_GROUPS_DEP.numpy()
    data = {
        "AMINO_ACIDS": list(rc.AMINO_ACID_s),
        "ONE_LETTER": rc.AMINO_ACID_one_letter,
        "SECONDARY_STRUCTURES": list(rc.SECONDARY_STRUCTURE_s),
        "MAX_ATOM": rc.MAX_ATOM,
        "MAX_RIGID": rc.MAX_RIGID,
        "MAX_TORSION": rc.MAX_TORSION,
        "MAX_SS": rc.MAX_SS,
        "RESIDUES": residues,
        "RIGID_TRANSFORMS": f32(rc.RIGID_TRANSFORMS_TENSOR.numpy()),
        "RIGID_TRANSFORMS_DEP": [int(x) for x in transforms_dep.ravel()],
        "RIGID_GROUPS": f32(rc.RIGID_GROUPS_TENSOR.numpy()),
        "RIGID_GROUPS_DEP": [int(x) for x in groups_dep.ravel()],
        "WIGNER_3J": w3j,
        "PDB_ATOM_NAMES": std,
    }
    shapes = {
        "RIGID_TRANSFORMS": list(rc.RIGID_TRANSFORMS_TENSOR.shape),
        "RIGID_GROUPS": list(rc.RIGID_GROUPS_TENSOR.shape),
    }
    with open(args.out, "w") as fout:
        fout.write("// Generated by tools/cg2all/export_constants.py from huhlim/cg2all (Apache-2.0) residue constants,\n")
        fout.write("// e3nn 0.5.1 Wigner-3j tensors and MDTraj PDB atom-name tables. Do not edit by hand.\n")
        fout.write(f"// Shapes: {json.dumps(shapes)}; lengths in nm (cg2all/MDTraj units).\n\n")
        for key, value in data.items():
            fout.write(f"export const {key} = {json.dumps(value, separators=(',', ':'))};\n")
    print("wrote", args.out)


if __name__ == "__main__":
    main()
