function extractMotifSpanFromAtoms(motifAtoms: string): { span: string; count: number } {
  const residues = motifAtoms
    .split(';')
    .map((part) => part.split(':')[0]?.trim() ?? '')
    .filter(Boolean);
  return { span: residues.join(', '), count: residues.length };
}

function buildAmeBenchmarkMeta(raw: AmeRawTask): BenchmarkTargetMeta {
  const { span, count } = extractMotifSpanFromAtoms(raw.motifAtoms);
  const ligandCrops = raw.ligands.map((l) => `A:${l}`).join(', ');
  const cropSegments = raw.cropSegmentsOverride ?? `${span}, ${ligandCrops}`;
  return {
    id: raw.id,
    name: `AME: ${raw.enzymeName}`,
    shortLabel: `AME: ${raw.shortName} (${raw.pdbId})`,
    category: 'enzyme-ligand',
    pdbId: raw.pdbId,
    sourceFamily: 'AME / RFD2–4',
    approxTokens: raw.approxTokens,
    tier: raw.approxTokens <= 215 ? 'fast' : 'standard',
    supportsGenie3: false,
    entities: ['protein', 'ligand'],
    biology: raw.biology,
    cropSegments,
    mcsaId: raw.mcsaId,
    ligands: [...raw.ligands],
    motifResidueCount: count,
    targetLength: raw.targetLength,
    conditionParams: {
      taskPreset: 'custom',
      contig: `${raw.targetLength}-${raw.targetLength}`,
      motifSpan: span,
      motifAtoms: raw.motifAtoms,
      unindexedMotif: true,
    },
  };
}

